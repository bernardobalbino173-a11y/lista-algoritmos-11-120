# Algoritmo 19: Testar funções matemáticas (raiz, exp, log, seno, potência, absoluto, conversão)
import math

print("raiz:", math.sqrt(64))
print("raiz com exp e log e round:", round(math.exp(0.5 * math.log(64))))
print("raiz com exp e log sem round:", math.exp(0.5 * math.log(64)))
print(f"{math.sin(45 * math.pi / 180) + 0.0001:.3f}")
print(f"potencia com exp e log e formatar: {math.exp(3 * math.log(8)) + 0.001:.3f}")
print("potencia com exp e log sem formatar:", math.exp(3 * math.log(8)))
print(f"potencia com operador ** e formatar: {8 ** 3:.3f}")
print("raiz cubica:", math.exp((1 / 3) * math.log(8)))
print("absoluto:", abs(-8))
print("absoluto:", abs(8))
print("convertendo para inteiro 5.5:", round(5.5))
print("convertendo para inteiro 6.5:", round(6.5))
print("convertendo para inteiro 6.5 + 0.0001:", round(6.5 + 0.0001))
print("convertendo para inteiro 5.45:", round(5.45))
print("convertendo para inteiro 5.51:", round(5.51))
print("convertendo para real 87:", float(87))
print("convertendo para int 3/4:", round(3 / 4))
