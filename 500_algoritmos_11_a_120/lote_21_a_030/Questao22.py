# Algoritmo 22: Testando hierarquia entre divisão (/), divisão inteira (//) e resto (%)
print("TESTANDO HIERARQUIA\n")
print("(18 / 6) % 2 é igual a:", (18 / 6) % 2)
print("20 / 4 // 2 é igual a:", 20 / 4 // 2)
print("É IGUAL a (20 / 4) // 2:", (20 / 4) // 2)
print("30 / 4 // 2 é igual a:", 30 / 4 // 2)
print("7.0 // 4:", 7.0 // 4)
print("7 // 4:", 7 // 4)
print("6.0 // 4:", 6.0 // 4)
print("6 // 4:", 6 // 4)
